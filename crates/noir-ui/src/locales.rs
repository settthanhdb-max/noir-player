#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn language_count_is_41() {
        assert_eq!(LANGUAGES.len(), 41);
    }

    #[test]
    fn codes_are_unique_and_nonempty() {
        let mut seen = std::collections::BTreeSet::new();
        for lang in LANGUAGES {
            assert!(!lang.code.is_empty());
            assert!(!lang.name.is_empty());
            assert!(seen.insert(lang.code), "duplicate code {}", lang.code);
        }
    }

    #[test]
    fn every_language_translates_the_core_set() {
        let required = CORE_KEYS;
        for lang in LANGUAGES.iter().skip(2) {
            for key in required {
                let found = lang.table.iter().any(|(k, _)| *k == *key);
                assert!(found, "{} is missing core key {}", lang.code, key);
            }
        }
    }

    #[test]
    fn core_keys_have_no_duplicates_per_table() {
        for lang in LANGUAGES.iter().skip(2) {
            let mut seen = std::collections::BTreeSet::new();
            for (k, _) in lang.table {
                assert!(seen.insert(*k), "duplicate key {} in {}", k, lang.code);
            }
        }
    }
}
