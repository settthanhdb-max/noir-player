//! Locale data for the 39 bundled non-English default languages.
//!
//! Each language ships a core table covering the player chrome (navigation,
//! playback states, control bar, dialogs, settings actions). Strings that a
//! language does not translate fall back to English at lookup time, never to
//! raw keys. The language list order must match
//! `noir_settings::schema::general::LANGUAGE_OPTIONS` (a unit test below
//! enforces exactly that) so persisted language indices stay meaningful.
//!
//! The order also keeps index 1 = Tiếng Việt for settings written by
//! versions that only shipped English + Vietnamese.

/// One bundled language: BCP-47 code, native display name (always rendered
/// with its own script, so no translation of names is needed), and the
/// translation table (empty for English/Vietnamese which keep full tables
/// in `i18n`).
#[derive(Debug, Clone, Copy)]
pub struct LangDef {
    pub code: &'static str,
    pub name: &'static str,
    pub table: &'static [(&'static str, &'static str)],
}

